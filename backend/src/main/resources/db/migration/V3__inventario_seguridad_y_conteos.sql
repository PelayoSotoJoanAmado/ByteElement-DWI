CREATE TABLE usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 rol VARCHAR(30) NOT NULL CHECK (rol IN ('ALMACEN','COMPRAS','SUPERVISOR','CONSULTA_COMERCIAL','ADMINISTRADOR')),
 activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE existencia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 producto_id BIGINT NOT NULL REFERENCES producto(id),
 almacen_id BIGINT NOT NULL REFERENCES almacen(id),
 cantidad BIGINT NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
 version BIGINT NOT NULL DEFAULT 0,
 UNIQUE (producto_id, almacen_id)
);
CREATE TABLE movimiento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 producto_id BIGINT NOT NULL REFERENCES producto(id),
 almacen_id BIGINT NOT NULL REFERENCES almacen(id),
 tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('ENTRADA','SALIDA','TRANSFERENCIA_ENTRADA','TRANSFERENCIA_SALIDA','AJUSTE_ENTRADA','AJUSTE_SALIDA')),
 cantidad BIGINT NOT NULL CHECK (cantidad > 0),
 autor VARCHAR(100) NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL,
 motivo VARCHAR(500) NOT NULL,
 saldo_resultante BIGINT NOT NULL CHECK (saldo_resultante >= 0),
 referencia VARCHAR(80) NOT NULL
);
CREATE INDEX ix_movimiento_par_fecha ON movimiento(producto_id,almacen_id,fecha,id);
CREATE TABLE conteo (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 producto_id BIGINT NOT NULL REFERENCES producto(id),
 almacen_id BIGINT NOT NULL REFERENCES almacen(id),
 movimiento_corte_id BIGINT NOT NULL DEFAULT 0,
 cantidad_fisica BIGINT NOT NULL CHECK (cantidad_fisica >= 0),
 saldo_corte BIGINT NOT NULL CHECK (saldo_corte >= 0),
 fecha_corte TIMESTAMP WITH TIME ZONE NOT NULL,
 autor VARCHAR(100) NOT NULL,
 motivo VARCHAR(500) NOT NULL,
 confirmado BOOLEAN NOT NULL DEFAULT FALSE,
 confirmado_por VARCHAR(100),
 confirmado_en TIMESTAMP WITH TIME ZONE,
 movimiento_id BIGINT UNIQUE REFERENCES movimiento(id),
 CHECK ((confirmado = FALSE AND confirmado_por IS NULL AND confirmado_en IS NULL) OR
        (confirmado = TRUE AND confirmado_por IS NOT NULL AND confirmado_en IS NOT NULL))
);
CREATE TABLE corte_stock (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lote VARCHAR(36) NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL,
 autor VARCHAR(100) NOT NULL,
 producto_id BIGINT NOT NULL REFERENCES producto(id),
 almacen_id BIGINT NOT NULL REFERENCES almacen(id),
 sku VARCHAR(50) NOT NULL,
 critico BOOLEAN NOT NULL,
 cantidad BIGINT NOT NULL CHECK (cantidad >= 0),
 minimo BIGINT,
 maximo BIGINT,
 UNIQUE(lote,producto_id,almacen_id),
 CHECK ((minimo IS NULL AND maximo IS NULL) OR (minimo >= 0 AND maximo > minimo))
);
CREATE INDEX ix_corte_fecha ON corte_stock(fecha,id);
