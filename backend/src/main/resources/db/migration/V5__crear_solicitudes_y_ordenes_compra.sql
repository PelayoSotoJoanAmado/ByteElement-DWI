-- V5: Solicitudes de compra (reposición) y Órdenes de compra internas
CREATE TABLE solicitud_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    almacen_id BIGINT NOT NULL,
    cantidad BIGINT NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    enviada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    aprobada_en TIMESTAMP WITH TIME ZONE,
    revisado_por_id BIGINT,
    motivo_rechazo VARCHAR(255),
    duplicada_de_id BIGINT,
    clave_idempotencia VARCHAR(80),

    CONSTRAINT ck_solicitud_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    CONSTRAINT fk_solicitud_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_solicitud_producto FOREIGN KEY (producto_id) REFERENCES producto(id),
    CONSTRAINT fk_solicitud_almacen FOREIGN KEY (almacen_id) REFERENCES almacen(id),
    CONSTRAINT fk_solicitud_revisado_por FOREIGN KEY (revisado_por_id) REFERENCES usuario(id),
    CONSTRAINT fk_solicitud_duplicada FOREIGN KEY (duplicada_de_id) REFERENCES solicitud_compra(id)
);

CREATE INDEX ix_solicitud_usuario ON solicitud_compra(usuario_id);
CREATE INDEX ix_solicitud_producto ON solicitud_compra(producto_id);
CREATE INDEX ix_solicitud_almacen ON solicitud_compra(almacen_id);
CREATE INDEX ix_solicitud_estado ON solicitud_compra(estado);
CREATE INDEX ix_solicitud_enviada ON solicitud_compra(enviada_en);

CREATE TABLE orden_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    numero_orden VARCHAR(50) NOT NULL,
    urgente BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_urgencia VARCHAR(255),
    emitida_en TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'EMITIDA',
    monto_estimado NUMERIC(12, 2) NOT NULL DEFAULT 0.00,

    CONSTRAINT uk_orden_solicitud UNIQUE (solicitud_id),
    CONSTRAINT uk_orden_numero UNIQUE (numero_orden),
    CONSTRAINT ck_orden_estado CHECK (estado IN ('EMITIDA', 'ATENDIDA', 'CANCELADA')),
    CONSTRAINT fk_orden_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud_compra(id),
    CONSTRAINT fk_orden_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE INDEX ix_orden_usuario ON orden_compra(usuario_id);
CREATE INDEX ix_orden_emitida ON orden_compra(emitida_en);
CREATE INDEX ix_orden_urgente ON orden_compra(urgente);

